import hashlib
import hmac
import base64
import json
from urllib.parse import urlencode


def build_binance_signature(payload: dict | None = None, query_params: dict | None = None, body: str | None = None) -> str:
    """Genera la firma HMAC-SHA-256 requerida por Binance Pay para la autenticación."""
    secret = (os.environ.get('BINANCE_SECRET_KEY') or BINANCE_SECRET_KEY or '').strip()
    if not secret:
        return ''

    if payload is not None:
        canonical = json.dumps(payload, separators=(',', ':'), sort_keys=True)
    elif query_params is not None:
        canonical = urlencode(sorted(query_params.items()), doseq=True)
    elif body is not None:
        canonical = body
    else:
        canonical = ''

    return hmac.new(
        secret.encode('utf-8'),
        canonical.encode('utf-8'),
        hashlib.sha256,
    ).hexdigest()


def verify_binance_signature(payload: bytes, signature: str, secret: str | None = None) -> bool:
    """Valida el webhook firmado por Binance Pay."""
    secret_value = (secret or os.environ.get('BINANCE_SECRET_KEY') or BINANCE_SECRET_KEY or '').strip()
    if not secret_value or not signature:
        return False

    expected = hmac.new(
        secret_value.encode('utf-8'),
        payload,
        hashlib.sha256,
    ).hexdigest()
    return hmac.compare_digest(expected, signature)

